"""The app icon (window, taskbar) and the Windows identity that makes the taskbar use it."""

from __future__ import annotations

import sys
from pathlib import Path

from PySide6.QtGui import QIcon

ASSETS = Path(__file__).parent / "assets"
ICON_FILE = (
    ASSETS / "raspi-manager.ico"
)  # 16 to 256 px; regenerated by scripts/make-icon.py
APP_ID = "raspi-manager"


def app_icon() -> QIcon:
    return QIcon(str(ICON_FILE))


def set_windows_identity() -> None:
    """Without its own AppUserModelID the taskbar groups the window under pythonw.exe and shows
    Python's icon. Harmless elsewhere."""
    if sys.platform != "win32":
        return
    try:
        import ctypes

        ctypes.windll.shell32.SetCurrentProcessExplicitAppUserModelID(APP_ID)
    except (AttributeError, OSError):
        pass
